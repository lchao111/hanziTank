  function getHanziAudioFile(hanzi) {
    return Array.from(hanzi)
      .map((char) => `u${char.codePointAt(0).toString(16)}`)
      .join("-") + ".mp3";
  }

  function parseHanziAudioList(rawList) {
    const seen = new Set();
    const duplicates = [];
    const prompts = [];
    rawList.split(/\r?\n/).forEach((line) => {
      const normalized = line.trim().replace(/^[-*]\s*/, "").replace(/\*\*/g, "");
      if (!normalized || !normalized.includes("，")) return;
      const [hanzi, firstWord, secondWord] = normalized.split("，").map((part) => part.trim());
      if (!hanzi || !firstWord || !secondWord) return;
      if (seen.has(hanzi)) {
        duplicates.push({ hanzi, text: `${hanzi}，${firstWord}，${secondWord}` });
        return;
      }
      seen.add(hanzi);
      prompts.push({ hanzi, text: `${hanzi}，${firstWord}，${secondWord}`, file: getHanziAudioFile(hanzi) });
    });
    return { prompts, duplicates };
  }

  const parsed = parseHanziAudioList(rawHanziAudioList);
  const hanziAudioPrompts = parsed.prompts;
  const duplicateHanziAudioPrompts = parsed.duplicates;

  const hanziVoiceLines = Object.fromEntries(
    hanziAudioPrompts.map((item) => [item.hanzi, `assets/audio/hanzi/${item.file}`])
  );

  return {
    rawHanziAudioList,
    hanziAudioPrompts,
    duplicateHanziAudioPrompts,
    hanziVoiceLines,
    getHanziAudioFile,
    parseHanziAudioList
  };
